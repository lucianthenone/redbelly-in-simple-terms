// Packs the Lucide icons (ISC licence) and the official Redbelly logo files into
// src/video/icons.js so the stage can render offline with no network requests.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
// Drop comments and the fixed size on the root <svg> only; inner shapes keep their own width and height.
const clean = (s) => s.replace(/<!--[\s\S]*?-->/g, "").replace(/<svg[^>]*>/, (tag) => tag.replace(/\s(width|height)="[^"]*"/g, "")).replace(/\s+/g, " ").trim();

const icons = {};
for (const f of readdirSync(join(root, "assets/icons")).filter((f) => f.endsWith(".svg"))) {
  icons[f.replace(".svg", "")] = clean(readFileSync(join(root, "assets/icons", f), "utf8"));
}
const logos = {};
for (const [k, f] of Object.entries({
  horizontal: "redbelly-horizontal-negative.svg",
  isotypeWhite: "redbelly-isotype-white.svg",
  isotypeRed: "redbelly-isotype-red.svg",
})) {
  // Each logo keeps its own class names; prefix them so two logos never share a style rule.
  let svg = clean(readFileSync(join(root, "assets/brand", f), "utf8"));
  const classes = [...new Set([...svg.matchAll(/\.([a-z0-9-]+)\{/g)].map((m) => m[1]))];
  for (const c of classes) svg = svg.split(c).join(`${k}-${c}`);
  logos[k] = svg.replace(/<title>.*?<\/title>/, "");
}
writeFileSync(join(root, "src/video/icons.js"),
  "// Generated by build-icons.mjs. Lucide icons (ISC) and official Redbelly logo files.\n" +
  `window.ICONS = ${JSON.stringify(icons)};\nwindow.LOGOS = ${JSON.stringify(logos)};\n`);
console.log(`packed ${Object.keys(icons).length} icons and ${Object.keys(logos).length} logos`);
